def get_flaw_label(flaw_id: str) -> str:
    if flaw_id in FLAWS_CATALOG:
        emoji, name, _ = FLAWS_CATALOG[flaw_id]
        return f"{emoji} {name}"
    return flaw_id

def flaws_by_category() -> dict:
    result = {}
    for fid, (emoji, name, cat) in FLAWS_CATALOG.items():
        result.setdefault(cat, []).append((fid, emoji, name))
    return result
